import Foundation

/// Platform-independent logical point. Scene coordinates start at the top left.
public struct CorePoint: Codable, Equatable, Sendable {
    public var x: Double
    public var y: Double

    public init(x: Double, y: Double) {
        self.x = x
        self.y = y
    }
}

/// Logical dimensions in the same units as CorePoint (points/DIPs at the host).
public struct CoreSize: Codable, Equatable, Sendable {
    public var width: Double
    public var height: Double

    public init(width: Double, height: Double) {
        self.width = width
        self.height = height
    }
}
